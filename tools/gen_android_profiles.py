#!/usr/bin/env python3
"""Builds the Android client-profile catalog (devices, app builds, languages) shared by Mac and Android.

Source: a "<date>_Base.db" made by the reference generator in Professional mode with a large count
(its REGISTRATOR table lists every device / build / language the generator knows).
Writes:
  desktop/nicegram-desktop/Telegram/SourceFiles/settings/ggtg_android_profiles_data.h
  android/Telegram-GGTG/TMessagesProj/src/main/java/app/ggtg/GgtgAndroidProfilesData.kt
Usage: python3 tools/gen_android_profiles.py <android Base.db> <windows Base.db>
(the Windows one: Desktop profile with api_id 2040, lang pack tdesktop; only its DEVICE / SYSTEM names are used)
"""
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAC_OUT = os.path.join(ROOT, "desktop/nicegram-desktop/Telegram/SourceFiles/settings/ggtg_android_profiles_data.h")
KT_OUT = os.path.join(ROOT, "android/Telegram-GGTG/TMessagesProj/src/main/java/app/ggtg/GgtgAndroidProfilesData.kt")
BRANDS = ["Xiaomi", "Motorola", "Huawei", "Samsung", "Realme"]


def load(path):
    rows = sqlite3.connect(path).execute(
        "select DEVICE, SDK, APP_VERSION, LANG_CODE, SYSTEM_LANG_CODE from REGISTRATOR").fetchall()
    devices, builds, langs = set(), set(), set()
    for device, sdk, build, lang, system in rows:
        brand = next((b for b in BRANDS if device.startswith(b)), None)
        if brand is None:
            sys.exit("unknown brand in DEVICE: " + device)
        devices.add((brand, device[len(brand):], int(sdk.split()[1])))
        builds.add(build)
        langs.add((lang, system))
    key = lambda v: [int(x) for x in v.replace("(", "").replace(")", "").replace(".", " ").split()]
    return sorted(devices), sorted(builds, key=key), sorted(langs)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    devices, builds, langs = load(sys.argv[1])
    win = sqlite3.connect(sys.argv[2]).execute("select distinct SDK, DEVICE from REGISTRATOR order by 1, 2").fetchall()
    win_systems = sorted({system for system, _ in win})
    win_devices = sorted({device for _, device in win})
    head = "generated by tools/gen_android_profiles.py - do not edit by hand"

    with open(MAC_OUT, "w") as f:
        f.write("// ggtg: Android client-profile catalog (%d devices, %d builds, %d languages); %s.\n" % (len(devices), len(builds), len(langs), head))
        f.write("#pragma once\n\nnamespace Ggtg::AndroidProfiles {\n\n")
        f.write("// brand, model, SDK: the model only ever appears with its own Android version.\n")
        f.write("inline constexpr const char *kDevices[] = {\n")
        for brand, model, sdk in devices:
            f.write('\t"%s|%s|%d",\n' % (brand, model, sdk))
        f.write("};\n\n// Real Telegram Android builds: versionName (versionCode).\ninline constexpr const char *kBuilds[] = {\n")
        for b in builds:
            f.write('\t"%s",\n' % b)
        f.write("};\n\n// cloud language code, system (Android locale) code.\ninline constexpr const char *kLangs[] = {\n")
        for lang, system in langs:
            f.write('\t"%s|%s",\n' % (lang, system))
        f.write("};\n\n} // namespace Ggtg::AndroidProfiles\n\n")
        f.write("namespace Ggtg::DesktopProfiles {\n\n// Windows laptops of the Desktop profile (api_id 2040): real model codes, one system string.\n")
        f.write("inline constexpr const char *kWindowsSystems[] = {\n")
        for x in win_systems:
            f.write('\t"%s",\n' % x)
        f.write("};\n\ninline constexpr const char *kWindowsDevices[] = {\n")
        for x in win_devices:
            f.write('\t"%s",\n' % x)
        f.write("};\n\n} // namespace Ggtg::DesktopProfiles\n")

    with open(KT_OUT, "w") as f:
        f.write("package app.ggtg\n\n// ggtg: Android client-profile catalog (%d devices, %d builds, %d languages); %s.\n" % (len(devices), len(builds), len(langs), head))
        f.write("internal object GgtgAndroidProfilesData {\n")
        f.write("    /** brand|model|SDK: the model only ever appears with its own Android version. */\n    val devices = listOf(\n")
        for brand, model, sdk in devices:
            f.write('        "%s|%s|%d",\n' % (brand, model, sdk))
        f.write("    )\n\n    /** Real Telegram Android builds: versionName (versionCode). */\n    val builds = listOf(\n")
        for b in builds:
            f.write('        "%s",\n' % b)
        f.write("    )\n\n    /** cloud language code|system (Android locale) code. */\n    val langs = listOf(\n")
        for lang, system in langs:
            f.write('        "%s|%s",\n' % (lang, system))
        f.write("    )\n}\n")
    print(len(devices), "devices,", len(builds), "builds,", len(langs), "languages")


main()
