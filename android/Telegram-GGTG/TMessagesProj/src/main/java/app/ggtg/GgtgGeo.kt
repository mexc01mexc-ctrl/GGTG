    fun matchForPhone(rawPhone: String): GeoMatch {
        val digits = rawPhone.filter(Char::isDigit)
        for (item in phoneTable) {
            if (digits.startsWith(item.prefix)) {
                return GeoMatch(item.country, item.tz, item.sys, item.cloud)
            }
        }
        return GeoMatch("US", -18000, "en-US", "en")
    }

